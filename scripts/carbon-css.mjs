// Compiles Carbon's Sass (styles/carbon.scss) to app/carbon.css. Runs before `dev` and `build`.
// Plain Sass, not Next.js: Turbopack can't resolve Carbon's relative imports on Windows
// (https://github.com/vercel/next.js/issues/86431).
import { existsSync, realpathSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";
import { compile } from "sass";

const root = fileURLToPath(new URL("..", import.meta.url));

/**
 * Finds `@carbon/react/scss/theme` like Node does: the nearest node_modules above the importing file.
 * Always the real path (pnpm links packages): one URL per file, so Sass loads each module once.
 */
export const nodeModules = {
  findFileUrl(url, { containingUrl }) {
    if (url.startsWith(".") || url.includes(":")) return null; // relative: Sass does it
    const parts = url.split("/");
    const n = url.startsWith("@") ? 2 : 1;
    const pkg = parts.slice(0, n).join("/");
    let dir = containingUrl?.protocol === "file:" ? dirname(fileURLToPath(containingUrl)) : root;
    for (;;) {
      const found = join(dir, "node_modules", pkg);
      if (existsSync(found)) return pathToFileURL(join(realpathSync(found), ...parts.slice(n)));
      if (dirname(dir) === dir) return null;
      dir = dirname(dir);
    }
  },
};

const { css } = compile(join(root, "styles/carbon.scss"), {
  importers: [nodeModules],
  style: "compressed",
  quietDeps: true, // Carbon's own deprecation warnings
  charset: false, // no BOM: the file starts with our comment
});
writeFileSync(join(root, "app/carbon.css"), `/* Generated by scripts/carbon-css.mjs. Do not edit. */\n${css}\n`);
console.log(`app/carbon.css: ${Math.round(css.length / 1024)} KB`);
